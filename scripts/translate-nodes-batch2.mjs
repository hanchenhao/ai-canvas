// Final glue / cleanup patterns applied AFTER substitution.
const CLEANUP_PATTERNS = [
  // Strip trailing plural "s" left after a Chinese char (image/video/mode/format/etc.).
  [/([一-龥])s\b/g, '$1'],
  [/([一-龥])s(?=\s|$|[,.;:)！？，。；：）])/g, '$1'],
  // Collapse double-spaces.
  [/\s{2,}/g, ' '],
  // Fix "的的" repetition.
  [/的的/g, '的'],
  // Common awkward residues: punctuation cleanup.
  [/，\s*\./g, '。'],
  [/\.\s*\./g, '。'],
  // Trim leading/trailing whitespace.
  [/^\s+|\s+$/g, ''],
  // "的。" -> "。"
  [/的。/g, '。'],
];

function translateDescription(text) {
  if (!text) return text;
  let out = text;
  for (const [re, repl] of DESC_PATTERNS) {
    out = out.replace(re, repl);
  }
  for (const [re, repl] of CLEANUP_PATTERNS) {
    out = out.replace(re, repl);
  }
  return out;
}

function translateTitle(text) {
  if (!text) return text;
  let out = text;
  for (const [re, repl] of TITLE_PATTERNS) {
    out = out.replace(re, repl);
  }
  return out;
}

function translatePropTitle(text) {
  if (!text) return text;
  if (PROP_TITLE_DICT[text]) return PROP_TITLE_DICT[text];
  // Apply title fallback patterns.
  let out = text;
  for (const [re, repl] of TITLE_PATTERNS) {
    out = out.replace(re, repl);
  }
  return out;
}

// ─── Main translation loop ───
let translatedCount = 0;
const perPrefixCount = {};

for (const [key, node] of Object.entries(en)) {
  if (!isTarget(key)) continue;
  if (zh[key]) continue;

  const newNode = {};
  if (node.title) {
    newNode.title = translateTitle(node.title);
  }
  if (node.description) {
    newNode.description = translateDescription(node.description);
  }
  if (node.properties) {
    newNode.properties = {};
    for (const [pk, pv] of Object.entries(node.properties)) {
      const newProp = {};
      if (pv.title) newProp.title = translatePropTitle(pv.title);
      else if ('title' in pv) newProp.title = pv.title;
      if (pv.description) newProp.description = translateDescription(pv.description);
      newNode.properties[pk] = newProp;
    }
  }
  zh[key] = newNode;
  translatedCount++;
  const prefix = TARGET_PREFIXES.find((p) => key.startsWith(p));
  perPrefixCount[prefix] = (perPrefixCount[prefix] || 0) + 1;
}

// Sort keys for stable output.
const sorted = {};
for (const k of Object.keys(zh).sort()) {
  sorted[k] = zh[k];
}

fs.writeFileSync(ZH_PATH, JSON.stringify(sorted, null, 2) + '\n', 'utf8');

